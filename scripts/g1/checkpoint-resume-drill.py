#!/usr/bin/env python3
"""G1: interrupt YOLO training after a real checkpoint, recover it from S3, and resume.

GPU-OFF: --dry-run validates dataset and configuration without importing torch.
GPU-ON: require G1 CUDA, AWS Instance Profile, and an otherwise idle GPU.
"""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import time


def stamp():
    return datetime.now(timezone.utc).isoformat()


def cmd(args, **kwargs):
    return subprocess.run(args, check=True, **kwargs)


def checkpoint_state(path):
    # Only inspect files generated by our own trusted training process.
    import torch
    data = torch.load(str(path), map_location="cpu", weights_only=False)
    epoch = data.get("epoch")
    optimizer = data.get("optimizer")
    if not isinstance(epoch, int) or epoch < 0 or optimizer is None:
        return None
    return {"epoch_zero_based": epoch, "has_optimizer": True}


def stop_training(process):
    if process.poll() is not None:
        return
    os.killpg(process.pid, signal.SIGKILL)
    process.wait(timeout=20)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--session", required=True)
    p.add_argument("--dataset", type=Path, default=Path("datasets/coco2017-perf-5k"))
    p.add_argument("--output", type=Path, default=Path("artifacts/g1-resume"))
    p.add_argument("--bucket", default="shared-gpu-cluster-351889159717-ap-northeast-2-an")
    p.add_argument("--region", default="ap-northeast-2")
    p.add_argument("--epochs", type=int, default=12)
    p.add_argument("--stop-after-epoch", type=int, default=2,
                   help="Interrupt after this many completed epochs have been checkpointed")
    p.add_argument("--timeout-seconds", type=int, default=1800)
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9_-]+", a.session):
        p.error("Use only letters, numbers, hyphen and underscore for session")
    if not (2 <= a.stop_after_epoch < a.epochs) or a.timeout_seconds < 60:
        p.error("Need 2 <= stop-after-epoch < epochs and timeout >= 60")
    dataset = a.dataset.resolve()
    if not (dataset / "manifest.json").is_file():
        p.error(f"Dataset missing: {dataset}")
    root = (a.output / a.session).resolve()
    if root.exists():
        p.error(f"Refusing to overwrite existing session: {root}")
    prefix = f"s3://{a.bucket}/results/g1-resume/{a.session}"
    if a.dry_run:
        print(json.dumps({
            "mode": "DRY-RUN", "dataset": str(dataset), "epochs": a.epochs,
            "checkpoint_epoch": a.stop_after_epoch, "s3_checkpoint": prefix + "/last.pt",
            "output": str(root), "effects": "no GPU, no S3 writes, no local output"
        }, indent=2))
        return

    import torch
    if not torch.cuda.is_available():
        p.error("CUDA GPU required; run on G1, not local WSL")
    cmd(["aws", "sts", "get-caller-identity", "--region", a.region], stdout=subprocess.DEVNULL)
    root.mkdir(parents=True)
    run_dir = root / "training"
    weights = run_dir / "weights" / "last.pt"
    log_path = root / "training.log"
    report = {"session": a.session, "started_utc": stamp(), "status": "started",
              "dataset": str(dataset), "s3_checkpoint": prefix + "/last.pt"}
    training_script = (
        "import sys; from ultralytics import YOLO; "
        "YOLO('yolo11n.pt').train(data=sys.argv[1],epochs=int(sys.argv[2]),"
        "batch=8,workers=2,imgsz=640,seed=42,device=0,cache=False,"
        "deterministic=True,save=True,save_period=1,val=True,plots=False,"
        "project=sys.argv[3],name='training',exist_ok=False)"
    )
    process = None
    checkpoint = None
    try:
        with log_path.open("w", encoding="utf-8") as log:
            process = subprocess.Popen([
                sys.executable, "-u", "-c", training_script,
                str(dataset / "data.yaml"), str(a.epochs), str(root)
            ], stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
            deadline = time.monotonic() + a.timeout_seconds
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError(f"Training exited before checkpoint capture: code {process.returncode}")
                # save_period=1 creates epochN.pt after each completed epoch.
                candidate = run_dir / "weights" / f"epoch{a.stop_after_epoch - 1}.pt"
                if candidate.is_file():
                    try:
                        checkpoint = checkpoint_state(candidate)
                    except (OSError, RuntimeError, EOFError, ValueError):
                        checkpoint = None  # file may still be mid-write
                    if checkpoint and checkpoint["epoch_zero_based"] >= a.stop_after_epoch - 1:
                        # Upload the stable epochN.pt, not last.pt which may still be written.
                        cmd(["aws", "s3", "cp", str(candidate), prefix + "/last.pt",
                             "--region", a.region, "--only-show-errors"])
                        report["s3_uploaded_utc"] = stamp()
                        report["saved_epoch_zero_based"] = checkpoint["epoch_zero_based"]
                        break
                time.sleep(2)
            if not checkpoint:
                raise TimeoutError("Checkpoint was not captured before deadline")
            stop_training(process)
            report["killed_utc"] = stamp()
        # Require that S3 is the restoration source.
        weights.unlink(missing_ok=True)
        for part in run_dir.glob("weights/epoch*.pt"):
            part.unlink()
        cmd(["aws", "s3", "cp", prefix + "/last.pt", str(weights),
             "--region", a.region, "--only-show-errors"])
        restored = checkpoint_state(weights)
        if restored != checkpoint:
            raise RuntimeError("Downloaded checkpoint state differs from uploaded source")
        report["restored_utc"] = stamp()
        report["status"] = "restored"
        resume_script = (
            "import sys; from ultralytics import YOLO; "
            "YOLO(sys.argv[1]).train(resume=True)"
        )
        with (root / "resume.log").open("w", encoding="utf-8") as log:
            result = subprocess.run(
                [sys.executable, "-u", "-c", resume_script, str(weights)],
                stdout=log, stderr=subprocess.STDOUT, check=False, timeout=a.timeout_seconds
            )
        report["resume_exit_code"] = result.returncode
        if result.returncode:
            raise RuntimeError(f"Resume failed: code={result.returncode}; inspect resume.log")
        # At completion, original final weights may be stripped: do not check optimizer here.
        results = run_dir / "results.csv"
        if not results.is_file():
            raise RuntimeError("Resume finished but results.csv missing")
        report["status"] = "resume_completed"
        report["completed_utc"] = stamp()
        print("[OK] S3 checkpoint restored and resumed training completed", flush=True)
    except BaseException as exc:
        report["status"] = "failed"
        report["failure"] = f"{type(exc).__name__}: {exc}"
        raise
    finally:
        if process is not None:
            stop_training(process)
        report["finished_utc"] = stamp()
        (root / "experiment.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
